/// Derives the 4-emoji Telegram encryption verification fingerprint from the call encryption key.
pub fn derive_call_emojis(key: &[u8]) -> Vec<String> {
    if key.is_empty() {
        return vec!["🍎".into(), "🚀".into(), "🌟".into(), "🐱".into()];
    }

    let hash = Sha256::digest(key);
    let n = TELEGRAM_CALL_EMOJIS.len();
    (0..4)
        .map(|i| {
            let offset = i * 8;
            let chunk: [u8; 8] = hash[offset..offset + 8].try_into().unwrap_or_default();
            let val = u64::from_le_bytes(chunk);
            TELEGRAM_CALL_EMOJIS[(val as usize) % n].to_string()
        })
        .collect()
}

/// Formats call duration in mm:ss (or hh:mm:ss if >= 1 hour).
pub fn format_call_duration(seconds: u32) -> String {
    let h = seconds / 3600;
    let m = (seconds % 3600) / 60;
    let s = seconds % 60;
    if h > 0 { format!("{h:02}:{m:02}:{s:02}") } else { format!("{m:02}:{s:02}") }
}
